#!/usr/bin/env python
"""Generate docs/dataset_inventory.md and data/inventory/table_probe.json.

The document is generated so that every number in it comes from the corpus
rather than from prose that drifts. Narrative observations are constants below;
counts, page classes and table-probe results are measured on every run.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pymupdf  # noqa: E402

from mediread.config import DATA_DIR, DOCS_DIR, INVENTORY_DIR, RAW_DIR  # noqa: E402
from mediread.ingest.inspect import document_profile  # noqa: E402
from mediread.ingest.structure import measure_table_structure  # noqa: E402

PROFILE_NOTES = {
    "digital": "selectable text, no page-body raster",
    "mixed": "digital text plus a full-page raster on page 1",
}


def load_inventory() -> dict:
    path = INVENTORY_DIR / "dataset_inventory.json"
    if not path.exists():
        raise SystemExit("run tooling/survey_dataset.py first")
    return json.loads(path.read_text())


def table_probe_all(reports: list[dict]) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for report in reports:
        if report.get("duplicate_of"):
            continue
        doc = pymupdf.open(RAW_DIR / report["source_filename"])
        pages = {}
        try:
            for page_number in range(1, doc.page_count + 1):
                probe = measure_table_structure(doc[page_number - 1])
                pages[str(page_number)] = probe.to_dict()
        finally:
            doc.close()
        out[report["report_id"]] = pages
    return out


def duplicate_summary(reports: list[dict]) -> tuple[list[str], dict]:
    groups: dict[str, list[str]] = {}
    for report in reports:
        groups.setdefault(report["sha256"], []).append(report["source_filename"])
    dup_lines = [
        f"- `{digest[:12]}` — {len(names)} identical files: " + ", ".join(f"`{n}`" for n in names)
        for digest, names in groups.items()
        if len(names) > 1
    ]
    return dup_lines, groups


def main() -> int:
    data = load_inventory()
    reports = data["reports"]
    unique = [r for r in reports if not r.get("duplicate_of")]
    probes = table_probe_all(reports)
    (INVENTORY_DIR / "table_probe.json").write_text(json.dumps(probes, indent=2), encoding="utf-8")

    total_pages = sum(r["page_count"] for r in unique)
    class_counts = Counter()
    for report in unique:
        class_counts.update(report["page_classes"])
    dup_lines, groups = duplicate_summary(reports)

    lines: list[str] = []
    add = lines.append

    add("# Dataset inventory — laboratory report corpus")
    add("")
    add("Generated by `tooling/build_inventory_doc.py` from the PDFs in `medical reports/`.")
    add("Regenerate with:")
    add("")
    add("```bash")
    add("python tooling/survey_dataset.py          # structural survey")
    add("python tooling/build_inventory_doc.py     # this document")
    add("```")
    add("")
    add("## 1. Files received")
    add("")
    add(f"- **{data['file_count']} PDF files** were supplied.")
    add(f"- They contain **{data['unique_documents']} unique documents** "
        f"({data['file_count'] - data['unique_documents']} file(s) are byte-identical duplicates).")
    add(f"- Unique documents hold **{total_pages} pages** in total.")
    add("")
    add("The brief describes 13 reports. The workspace holds 12 PDF files, of which 3 are the")
    add("same document; the analysis therefore covers **10 distinct reports / 66 pages**. If a")
    add("13th report exists, it was not present in `medical reports/` at inspection time.")
    add("")
    add("### Duplicate groups")
    add("")
    for line in dup_lines:
        add(line)
    add("")
    add("Duplicates are byte-identical (same SHA-256), so they add no evaluation diversity and")
    add("are counted once everywhere below.")
    add("")
    add("## 2. Report-level inventory")
    add("")
    add("| # | Report id | Source file | Pages | Profile | Page classes | Text chars | Table pages (probe) |")
    add("|---|-----------|-------------|------:|---------|--------------|-----------:|--------------------:|")
    for index, report in enumerate(sorted(unique, key=lambda r: (r["page_count"], r["source_filename"])), 1):
        classes = ", ".join(f"{k}:{v}" for k, v in sorted(report["page_classes"].items()))
        text_chars = sum(p["char_count"] for p in report["pages"])
        report_probes = probes.get(report["report_id"], {})
        table_pages = sum(1 for p in report_probes.values() if p["usable"])
        add(
            f"| {index} | `{report['report_id']}` | `{report['source_filename']}` | "
            f"{report['page_count']} | {report['document_profile']} | {classes} | "
            f"{text_chars:,} | {table_pages}/{report['page_count']} |"
        )
    add("")
    add(f"**Page classes across the corpus:** " + ", ".join(
        f"`{name}` {count}" for name, count in sorted(class_counts.items())
    ))
    add("")
    add("No page in this corpus is image-only or purely scanned. Every page has either a full")
    add("selectable text layer or a full-page raster **with a live text overlay** (page 1).")
    add("")
    add("## 3. Page-level classification")
    add("")
    add("Classes are produced by `mediread.ingest.inspect.classify_page` from measured signals:")
    add("text volume, text area coverage, raster area coverage, vector rules and text-integrity")
    add("heuristics. Rules, in order:")
    add("")
    add("| Condition | Class |")
    add("|-----------|-------|")
    add("| no text, no images | `blank` |")
    add("| raster covers >= 85 % of the page and text exists | `hybrid` |")
    add("| raster covers >= 85 % of the page, no text | `scanned_image` |")
    add("| raster >= 30 % and text area < 6 % | `hybrid` |")
    add("| credible text layer (>= 120 chars, >= 15 words) | `digital_text` |")
    add("| small text layer, no dominant raster | `hybrid` |")
    add("")

    for report in sorted(unique, key=lambda r: (r["page_count"], r["source_filename"])):
        add(f"### `{report['source_filename']}` — {report['page_count']} pages")
        add("")
        add("| Page | Class | Chars | Words | Text cov | Image cov | Largest image | H/V rules | Table rows (probe) | Probe notes |")
        add("|-----:|-------|------:|------:|---------:|----------:|---------------|-----------|--------------------|-------------|")
        report_probes = probes.get(report["report_id"], {})
        for page in report["pages"]:
            probe = report_probes.get(str(page["page_number"]), {})
            largest = page["largest_image_px"]
            largest_text = f"{largest[0]}x{largest[1]}" if largest else "—"
            add(
                f"| {page['page_number']} | {page['page_class']} | {page['char_count']} | "
                f"{page['word_count']} | {page['text_area_ratio']:.0%} | {page['image_area_ratio']:.0%} | "
                f"{largest_text} | {page['horizontal_rule_count']}/{page['vertical_rule_count']} | "
                f"{probe.get('table_row_count', '—')} | {'; '.join(probe.get('notes', [])) or '—'} |"
            )
        add("")

    add("## 4. Observations that drive the ingestion design")
    add("")
    add("**4.1 Two producers, one dominant layout.** Nine unique reports are iTextSharp 5.5.13")
    add("exports (`producer` in the survey JSON). One (`4bc2a93c…`, a haemoglobin")
    add("electrophoresis report) is a *Microsoft Print to PDF* capture with subset fonts and no")
    add("useful document structure. The ingestion layer therefore cannot assume a single")
    add("producer's table model.")
    add("")
    add("**4.2 The tables are whitespace-aligned, not ruled.** Vertical vector rules are")
    add("essentially absent (0-6 per document) and horizontal rules are sparse. Table geometry")
    add("lives in text positions. Direct text extraction preserves rows well *at the word level*")
    add("(test name, value, unit and range keep their relative order and x-positions), but the")
    add("naive `get_text()` line order does not: every cell is emitted as its own text line. Row")
    add("reconstruction from word boxes is mandatory. See §5 for measured evidence.")
    add("")
    add("**4.3 Page 1 of every multi-page report is a hybrid page.** It is a full-page 1239x1753")
    add("PNG (150 DPI) carrying the laboratory's designed letterhead, **with a live text overlay**")
    add("for the summary fields (patient, panel, date, status). Treating it as a scan loses the")
    add("overlay; treating it as digital text loses the letterhead. It is routed as `hybrid`: the")
    add("text layer is kept, the raster is OCR'd, and OCR lines already covered by the text layer")
    add("are dropped by region overlap so nothing is duplicated.")
    add("")
    add("**4.4 Page furniture accounts for most raster area on digital pages.** Every content")
    add("page carries a 1600-2456 px banner/footer image, 40x40 marker icons and a signature")
    add("stamp, covering ~18-20 % of the page. A page is not 'scanned' because 20 % of it is an")
    add("image; the classifier therefore uses relative coverage and the 85 % full-page rule.")
    add("")
    add("**4.5 Cell values must never pass through a layout model.** PyMuPDF's layout-model")
    add("table finder (`page.find_tables()`, backed by ONNX models) was measured on this corpus")
    add("and silently corrupts numeric cells:")
    add("")
    add("```text")
    add("65.63   -> '65 63\\n.'       45-129  -> '45 129\\n-'")
    add("0.58    -> '0 58\\n.'        0.13    -> '0 13\\n.'")
    add("```")
    add("")
    add("A moved decimal point is a wrong laboratory value. MediRead reconstructs columns")
    add("geometrically over **verbatim** MuPDF word tokens, so every character and decimal point")
    add("comes from the PDF itself.")
    add("")
    add("**4.6 The authored text layer has its own defects.** The single-page report uses")
    add("ligature-glyph substitutions (`ﬁndings`, `suggesƟve`), and page 11 of `0d3182cc…`")
    add("prints `pq` where `pg` is meant — verified on the rendered page, so the typo is the")
    add("laboratory's, not an extraction artefact. Both are preserved verbatim and surfaced, never")
    add("silently repaired.")
    add("")
    add("**4.7 Content mixes tables with prose.** Clinical-significance paragraphs and method")
    add("notes sit between result rows. Row classification (result row vs prose) is required")
    add("before any laboratory extraction; the evaluation ground truth applies the same filter.")
    add("")
    add("**4.8 Section variety is real.** The 12-page report alone contains urine analysis (with")
    add("qualitative results such as `PALE YELLOW`, `ABSENT`), PT/INR, liver function, phosphorus,")
    add("electrolytes, kidney function with eGFR, HbA1c and a two-block hemogram with 5- and")
    add("4-column sub-tables. A single fixed column schema will not work.")
    add("")
    add("## 5. Does direct extraction preserve table structure?")
    add("")
    add("Yes at the word level, no at the line level. Measured on the corpus:")
    add("")
    add("- Word boxes are exact and stable; `page.get_text('words')` returns 100 % of the")
    add("  visible tokens for digital pages.")
    add("- MuPDF's line grouping splits one visual row into up to five line objects (one per")
    add("  cell). Summing `get_text()` output therefore produces a column-major-looking mess.")
    add("- Reconstructing rows from word y-centres and columns from horizontal gaps recovers")
    add("  structured rows on the dense pages: hemogram 29/29 rows, urine analysis 28/28,")
    add("  liver function 16/16, electrolytes 5/5. Sparse pages (one or two results) have no")
    add("  table band by design and are handled row-by-row.")
    add("")
    add("The probe in `data/inventory/table_probe.json` records, per page: row count, inferred")
    add("column count, multi-column row count, modal segment count, segmentation consistency and")
    add("whether the page is table-like. Pages with a single result row are reported as not")
    add("table-like, which is accurate rather than a failure.")
    add("")
    add("## 6. Unusual formatting and extraction challenges")
    add("")
    add("| Challenge | Where | Handling |")
    add("|-----------|-------|----------|")
    add("| Cell-per-line text layer | all digital pages | row reconstruction from word boxes |")
    add("| Whitespace-aligned columns, no rules | all digital pages | x-gap clustering + column signature voting |")
    add("| Full-page raster with text overlay | page 1 of 8 reports | hybrid region merge |")
    add("| 150 DPI page raster | page 1 of 8 reports | native pixels, no re-render |")
    add("| Ligature glyph substitutions | `4bc2a93c…` | preserved verbatim; flagged uncertain downstream |")
    add("| Decimal values everywhere | all | verbatim tokens; decimals never re-segmented |")
    add("| Qualitative results | urine analysis | treated as result rows, not numbers |")
    add("| Superscript units (`10³/µL`) | hemogram | kept as text; unit normalisation only in metrics |")
    add("| Multi-block tables with different widths | hemogram | per-band column inference |")
    add("| Prose interleaved with tables | liver/kidney/electrolyte pages | row filtering |")
    add("| Different producer, subset fonts | `4bc2a93c…` | direct extraction still works; no special case |")
    add("")
    add("## 7. What this corpus does *not* contain")
    add("")
    add("- **No genuinely scanned laboratory table.** The only rasters are page-1 letterheads.")
    add("  OCR of real scan noise / skew / camera perspective is therefore **not** validated by")
    add("  this dataset. Evaluation of OCR uses pages rendered from digital PDFs (labelled")
    add("  `rendered`) plus synthetic degradations, and this limitation is repeated in the")
    add("  evaluation report.")
    add("- **No camera photographs.** Not testable without new data.")
    add("- **No other laboratory's format** except the one Microsoft Print to PDF report.")
    add("- **No negative or scientific-notation values**, no multi-column layouts, no")
    add("  right-to-left text, no handwritten annotations.")
    add("- **No multi-report PDFs** (one patient = one report).")
    add("")
    add("## 8. Consequences for the ingestion architecture")
    add("")
    add("1. Classification must be per page and must consider raster *coverage relative to text*,")
    add("   not text volume alone (rule 4.3/4.4).")
    add("2. The digital path is the primary path and must be exact: verbatim tokens, exact")
    add("   boxes, no layout model, no normalisation.")
    add("3. OCR is required for the hybrid page and for any future scanned page; it must be")
    add("   provider-agnostic because engine quality differs by content type (§ evaluation).")
    add("4. Region-level merging is required for hybrid pages, not whole-page choice.")
    add("5. Table reconstruction belongs downstream of text extraction and must tolerate")
    add("   multiple table blocks and single-row pages.")
    add("6. Evaluation must separate *rendered* from *raster* inputs and must weight numeric and")
    add("   unit tokens far above prose.")
    add("")

    out = DOCS_DIR / "dataset_inventory.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(lines)} lines)")
    print(f"wrote {INVENTORY_DIR / 'table_probe.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
