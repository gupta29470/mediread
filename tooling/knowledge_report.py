"""Generate the corpus coverage report and the reviewer queue.

Outputs (checked in, regenerated by hand):

* ``reports/knowledge-corpus.md``  — counts, categories, statuses, source and
  licensing coverage, ambiguous aliases, validation warnings.
* ``reports/knowledge-review-queue.md`` — one block per draft entry: its claims,
  the cited evidence excerpt (or a warning that only a source-level reference
  exists), and a sign-off line. A qualified reviewer works through this file.

Coverage is measured against the extraction corpus in ``artifacts/results/``: test
names that appear in real reports but are not in the package are listed explicitly,
so a missing test is visible instead of silently unsupported.
"""

from __future__ import annotations

import glob
import json
from collections import Counter
from pathlib import Path

from mediread.knowledge.package import load_package
from mediread.knowledge.store import KnowledgeStore
from mediread.knowledge.validate import validate_package

REPO = Path(__file__).resolve().parents[1]
PACKAGE = REPO / "knowledge" / "mediread-knowledge.json"
REPORTS = REPO / "reports"


def corpus_names() -> Counter:
    names: Counter = Counter()
    for path in glob.glob(str(REPO / "artifacts" / "results" / "*.results.json")):
        document = json.loads(Path(path).read_text())
        for result in document.get("results", []):
            raw = ((result.get("test") or {}).get("raw") or "").strip()
            if raw:
                names[raw] += 1
    return names


def main() -> None:
    package, report = load_package(PACKAGE)
    REPORTS.mkdir(exist_ok=True)

    names = corpus_names()
    covered, uncovered = [], []
    with KnowledgeStore.open(REPO / "artifacts" / "knowledge" / "mediread-knowledge.sqlite") as store:
        for name, count in names.most_common():
            result = store.lookup(name, include_statuses=("draft", "reviewed", "approved"))
            (covered if result.match_type != "unsupported" else uncovered).append((name, count))

    excerpt_counts = Counter()
    for entry in package.evidence:
        if "Quoted excerpt" in entry.supporting_excerpt_or_reference:
            excerpt_counts[entry.test_id] += 1

    lines = [
        "# Knowledge corpus report",
        "",
        f"Package `{package.knowledge_version}` · content hash `{package.content_hash}`",
        "",
        "| metric | value |",
        "|---|---|",
        f"| tests | {len(package.tests)} |",
        f"| sources | {len(package.sources)} |",
        f"| aliases (incl. canonical names) | {len(package.all_aliases())} |",
        f"| evidence rows | {len(package.evidence)} |",
        f"| tests with a quoted excerpt for at least one claim | {len(excerpt_counts)} |",
        f"| draft / reviewed / approved | "
        f"{package.status_counts()['draft']} / {package.status_counts()['reviewed']} / "
        f"{package.status_counts()['approved']} |",
        "",
        "## By category",
        "",
        "| category | tests |",
        "|---|---|",
    ]
    for category, count in package.category_counts().items():
        lines.append(f"| {category} | {count} |")
    lines += ["", "## Validation", ""]
    lines.append("No errors." if not report.errors else "Errors:\n" + "\n".join(f"- {e}" for e in report.errors))
    if report.warnings:
        lines.append("")
        lines.append("Warnings:")
        lines += [f"- {w}" for w in report.warnings]
    else:
        lines.append("")
        lines.append("No warnings.")
    lines += [
        "",
        "## Corpus coverage (test names seen in MediRead reports)",
        "",
        f"- names covered: **{len(covered)}** of {len(covered) + len(uncovered)}",
        f"- rows covered: **{sum(c for _, c in covered)}** of {sum(c for _, c in covered) + sum(c for _, c in uncovered)}",
        "",
    ]
    if uncovered:
        lines += ["| uncovered name | rows |", "|---|---|"]
        lines += [f"| {name} | {count} |" for name, count in uncovered]
    else:
        lines.append("Every name in the report corpus is covered.")
    lines += [
        "",
        "## Source and licensing coverage",
        "",
        "| source | licence | attribution | tests citing it |",
        "|---|---|---|---|",
    ]
    citing: Counter = Counter()
    for entry in package.evidence:
        citing[entry.source_id] += 1
    for source in package.sources:
        lines.append(
            f"| {source.source_id} | {source.content_license} | "
            f"{'yes' if source.attribution_requirements else 'MISSING'} | {citing[source.source_id]} |"
        )
    lines += ["", "## Ambiguous aliases", ""]
    ambiguous = report.stats.get("ambiguous_aliases") or {}
    if ambiguous:
        for alias, ids in ambiguous.items():
            lines.append(f"- `{alias}` → {', '.join(ids)} (lookup returns ambiguous; never permits)")
    else:
        lines.append("None.")
    lines += [
        "",
        "## Review state",
        "",
        "**No entry is approved.** Independent, qualified review has not happened, so the "
        "runtime default (approved only) permits nothing. That is correct behaviour.",
        "",
    ]
    (REPORTS / "knowledge-corpus.md").write_text("\n".join(lines))

    queue = [
        "# Knowledge review queue",
        "",
        "Every entry below is `draft`. A reviewer must check each claim against the cited",
        "source, then run:",
        "",
        "```",
        "python -m mediread.knowledge.cli set-status --package knowledge/mediread-knowledge.json \\",
        "    --test-id <id> --status reviewed --reviewer \"Name (role)\" --note \"what was checked\"",
        "```",
        "",
        "Entries with only a source-level reference (no quoted excerpt) need an excerpt added",
        "before they can be reviewed; they are marked below.",
        "",
    ]
    for test in sorted(package.tests, key=lambda item: item.test_id):
        evidence = package.evidence_for(test.test_id)
        quoted = [e for e in evidence if "Quoted excerpt" in e.supporting_excerpt_or_reference]
        queue += [f"## `{test.test_id}` — {test.canonical_name}", ""]
        queue.append(f"- category: {test.category} · content version {test.content_version} · "
                     f"status **{test.review_status}**")
        queue.append(f"- related tests: {', '.join(test.related_test_ids) or 'none'}")
        queue.append(f"- sources: {', '.join(source.source_id for source in package.sources_for(test.test_id))}")
        queue.append("")
        queue.append("| claim | evidence |")
        queue.append("|---|---|")
        for item in evidence:
            excerpt = item.supporting_excerpt_or_reference.replace("|", "\\|")
            if "Quoted excerpt" in excerpt:
                excerpt = excerpt.split("Quoted excerpt:", 1)[1].strip()
            else:
                excerpt = f"_(source-level only — add a quoted excerpt)_ {excerpt}"
            queue.append(f"| {item.claim_field} | {excerpt[:300]} |")
        if not quoted:
            queue.append("")
            queue.append("> No quoted excerpt for this entry.")
        queue += ["", "- [ ] reviewed by: __________  date: __________", ""]
    (REPORTS / "knowledge-review-queue.md").write_text("\n".join(queue))
    print(f"wrote {REPORTS/'knowledge-corpus.md'} and {REPORTS/'knowledge-review-queue.md'}")


if __name__ == "__main__":
    main()
